import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const root = process.cwd();
const packIds = ['genesis', 'exodus-judges', 'united-monarchy', 'divided-kingdom', 'exile-restoration', 'second-temple', 'gospels', 'acts-paul', 'revelation'];
const read = (pack, file) => fs.readFile(path.join(root, 'public', 'data', pack, file), 'utf8').then(JSON.parse);

function statusFor(source) {
  if (source.verificationStatus) return source.verificationStatus;
  if (source.kind === 'project-methodology') return 'project-authored';
  if (/supplied|research/i.test(source.verifiedAt || '')) return 'research-supplied';
  return 'needs-verification';
}

const records = [];
const errors = [];
for (const pack of packIds) {
  const sources = await read(pack, 'sources.json');
  for (const source of sources) {
    if (!source.id || !source.title) errors.push(`${pack}: source missing id/title`);
    if (!source.notes) errors.push(`${pack}/${source.id}: source notes are required for provenance context`);
    const status = statusFor(source);
    if (status === 'primary-verified' && (!source.url || !source.verifiedAt)) {
      errors.push(`${pack}/${source.id}: primary-verified requires both url and verifiedAt`);
    }
    records.push({
      pack,
      id: source.id,
      title: source.title,
      kind: source.kind || 'uncategorized',
      status,
      url: source.url || null,
      verifiedAt: source.verifiedAt || null,
      license: source.license || null,
      doi: source.doi || null,
      isbn: source.isbn || null
    });
  }
}

if (errors.length) {
  console.error(`Provenance audit failed with ${errors.length} error(s):`);
  for (const error of errors) console.error(` - ${error}`);
  process.exit(1);
}

const statusCounts = records.reduce((acc, record) => ({ ...acc, [record.status]: (acc[record.status] || 0) + 1 }), {});
const kindCounts = records.reduce((acc, record) => ({ ...acc, [record.kind]: (acc[record.kind] || 0) + 1 }), {});
const withUrl = records.filter((record) => record.url).length;
const withLicense = records.filter((record) => record.license).length;
const report = {
  schemaVersion: 1,
  note: 'Generated structural provenance report. It does not perform live web verification.',
  totals: { sources: records.length, withUrl, withLicense },
  statusCounts,
  kindCounts,
  records
};

const outDir = path.join(root, 'public', 'data', 'generated');
await fs.mkdir(outDir, { recursive: true });
await fs.writeFile(path.join(outDir, 'provenance-report.json'), JSON.stringify(report, null, 2) + '\n');

const lines = [
  '# Source Verification Queue',
  '',
  '> Generated by `npm run audit:provenance`. This is a structural review queue, **not** evidence that external sources were checked live. Web access was unavailable during Batch 11.',
  '',
  `- Total source records: **${records.length}**`,
  `- Project-authored records: **${statusCounts['project-authored'] || 0}**`,
  `- Research-supplied metadata records: **${statusCounts['research-supplied'] || 0}**`,
  `- External records still needing live verification: **${statusCounts['needs-verification'] || 0}**`,
  `- Records with a URL: **${withUrl}**`,
  `- Records with license metadata: **${withLicense}**`,
  '',
  '## Release rule',
  '',
  'Before describing v1.x as a scholarly/academic release, every external record used for a material geographic, archaeological, chronological, textual, or licensing claim should be checked against a primary/official source or a citable edition, and updated with stable locator metadata where available.',
  '',
  '## Queue',
  '',
  '| Pack | Source ID | Kind | Status | Locator | Title |',
  '|---|---|---|---|---|---|',
  ...records
    .filter((record) => record.status !== 'project-authored')
    .map((record) => `| ${record.pack} | \`${record.id}\` | ${record.kind} | ${record.status} | ${record.url ? `[URL](${record.url})` : '—'} | ${record.title.replaceAll('|', '\\|')} |`),
  '',
  '## What to capture during live verification',
  '',
  '- Stable official URL or DOI/ISBN/edition/page locator.',
  '- Exact license and attribution text for datasets and media.',
  '- Access/check date.',
  '- Whether the source supports the exact claim made by the atlas rather than only a related historical fact.',
  '- Any disagreement between primary evidence and modern reconstruction.',
  ''
];
await fs.writeFile(path.join(root, 'docs', 'SOURCE_VERIFICATION_QUEUE.md'), lines.join('\n'));
console.log(`Provenance audit passed structurally: ${records.length} sources; ${statusCounts['project-authored'] || 0} project-authored, ${(statusCounts['research-supplied'] || 0) + (statusCounts['needs-verification'] || 0)} external records queued for live verification.`);
